const {chromium}=require('playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/');
 await page.locator('#token').fill('wrong');await page.locator('#loginForm button').click();
 await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('token'));
 const token=fs.readFileSync('.env','utf8').match(/^API_TOKEN=(.+)$/m)[1].trim().replace(/^['"]|['"]$/g,'');
 await page.locator('#token').fill(token);await page.locator('#loginForm button').click();
 await page.locator('#app').waitFor({state:'visible'});
 await page.locator('#check').click();
 await page.waitForFunction(()=>document.querySelector('#checks').textContent.includes('demo'));
 await page.locator('#run').click();
 await page.waitForFunction(()=>document.querySelector('#report').textContent.includes('Расчётная сводка'));
 if(!await page.locator('#report').textContent().then(s=>s.includes('MOEX:TQBR:SBER')))throw Error('Missing SBER');
 await page.screenshot({path:'qa/desktop.png',fullPage:true});
 await page.reload();
 await page.locator('#login').waitFor({state:'visible'});
 if(await page.locator('#token').inputValue())throw Error('Token persisted');
 await page.locator('#token').fill(token);await page.locator('#loginForm button').click();
 await page.locator('#history button').first().click();
 await page.waitForFunction(()=>document.querySelector('#report').textContent.includes('Расчётная сводка'));
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw Error('Horizontal overflow');
 await page.screenshot({path:'qa/mobile.png',fullPage:true});
 await page.locator('#logout').click();await page.locator('#login').waitFor({state:'visible'});
 if(errors.length)throw Error(errors.join(';'));
 console.log('Browser checks passed: wrong token, login, run, report, persisted history, token cleared on reload, mobile layout, logout.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
