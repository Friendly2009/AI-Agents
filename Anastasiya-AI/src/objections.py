"""Conservative multi-label heuristic; categories are intentions, never outcomes."""
import re

# category: pattern, facts to verify, useful response, human handoff, prohibited claim
RULES = {
 'refusal': (r'не пишите|не звоните|отказываюсь|не записывайте|^/стоп$', 'актуальность отказа', 'принять отказ', 'только по просьбе', 'новые уговоры'),
 'price': (r'дорого|не по карману|стоимость|сколько стоит', 'тариф и состав по филиалу', 'назвать проверенную цену', 'индивидуальные условия', 'выдуманные скидки'),
 'time': (r'нет времени|неудобн|не успева|расписание', 'актуальное расписание', 'обсудить удобное время', 'нет подтверждённых слотов', 'обещание свободного места'),
 'age': (r'слишком мал|слишком взросл|по возрасту|возраст', 'возрастные требования программы', 'объяснить требования', 'границы возраста неизвестны', 'гарантия подходящего уровня'),
 'experience': (r'нет опыта|не умеет|с нуля|сложно', 'входные требования', 'рассказать подтверждённый формат старта', 'нужна оценка педагога', 'всем будет легко'),
 'interest': (r'неинтерес|не интерес|не понрав|не хочет', 'интерес ребёнка и содержание', 'принять отсутствие интереса или показать подходящий проект', 'нужен другой формат', 'обязательно понравится'),
 'trust': (r'не довер|обман|отзыв|мошен', 'проверяемые сведения о школе', 'дать проверяемый факт', 'нужны документы или разбор жалобы', 'выдуманные отзывы'),
 'program': (r'сомнева|программ[аеуы]|чему науч|какая польз', 'утверждённое содержание', 'объяснить наблюдаемые действия на занятии', 'детали методики неизвестны', 'гарантии баллов и результата'),
 'competitor': (r'другая школа|другой школе|конкурент|сравн', 'цель и проверенные отличия', 'сравнить по задаче клиента', 'нет сведений об условиях', 'непроверенная критика конкурента'),
 'think': (r'подума|не сейчас|пока не готов', 'нужна ли дополнительная информация', 'дать время без давления', 'только по запросу', 'ложный дефицит и срочность'),
}

def classify_all(text):
    return [name for name, rule in RULES.items() if re.search(rule[0],text or '',re.I)]

def classify(text):
    return next(iter(classify_all(text)), None)

def guidance(text):
    lines=[]
    for name in classify_all(text):
        _,facts,answer,human,forbidden=RULES[name]
        lines.append(f'{name}: проверить {facts}; ответ: {answer}; человек: {human}; нельзя: {forbidden}.')
    return ' Эвристика сомнений (не факт отказа): '+' '.join(lines) if lines else ''
